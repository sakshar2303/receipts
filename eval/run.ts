// `npm run eval`: scores Receipts on the hand-written cases and, when labels
// exist in eval/private/, on real sessions. Writes eval/results.md, which holds
// only aggregate numbers; no real transcript text leaves eval/private/.
import { writeFileSync } from "node:fs";
import path from "node:path";
import type { Io } from "../src/commands/check.js";
import { pickOllamaModel } from "../src/providers/select.js";
import { VERDICTS } from "../src/types.js";
import { LABELS_FILE, readLabels, realUnits, receiptForUnit, type Provenance } from "./lib/real.js";
import { pct, score, type Scores, type ScoredUnit } from "./lib/score.js";
import { flagScores, runSynthetic } from "./lib/synthetic.js";

const ROOT = process.cwd();
const io: Io = {
  write: () => undefined,
  isTTY: false,
  columns: 100,
  // Only a local model is ever used; hosted keys are dropped on purpose.
  env: process.env.OLLAMA_HOST ? { OLLAMA_HOST: process.env.OLLAMA_HOST } : {},
  cwd: ROOT,
};

const LABELLED_BY: Record<Provenance, string> = {
  hand: "labelled by hand with `npm run label`.",
  assistant:
    "labelled by an AI coding assistant reading the same evidence. **The author has not reviewed these labels yet**, so treat the numbers as provisional.",
  "assistant-reviewed":
    "given a first-pass label by an AI coding assistant reading the same evidence, then reviewed and corrected by the author.",
};

async function realScores(model: string | null): Promise<Scores | null> {
  const labels = readLabels();
  if (labels.units.length === 0) return null;
  const units = new Map((await realUnits()).map((u) => [u.key, u]));
  const scored: ScoredUnit[] = [];
  for (const l of labels.units) {
    const unit = units.get(l.key);
    if (!unit) continue;
    const receipt = await receiptForUnit(unit, io, model);
    const truth = l.claims.flatMap((c) =>
      c.truth === "not-a-claim" ? [] : [{ span: { start: c.start, end: c.end }, verdict: c.truth }],
    );
    scored.push({ truth, missed: l.missed, predicted: receipt.claims });
  }
  return score(scored);
}

function table(columns: [string, Scores | null][]): string {
  const live = columns.filter((c): c is [string, Scores] => c[1] !== null);
  const row = (label: string, f: (s: Scores) => string) =>
    `| ${label} | ${live.map(([, s]) => f(s)).join(" | ")} |`;
  return [
    `| Metric | ${live.map(([name]) => name).join(" | ")} |`,
    `| --- | ${live.map(() => "---:").join(" | ")} |`,
    row("Claim extraction precision", (s) => pct(s.extractionPrecision)),
    row("Claim extraction recall", (s) => pct(s.extractionRecall)),
    row("Verdict accuracy (claims found)", (s) => pct(s.verdictAccuracy)),
    row(
      "**False-verified rate**",
      (s) => `**${pct(s.falseVerifiedRate)}** (${s.falseVerified} of ${s.markedVerified})`,
    ),
    ...VERDICTS.map((v) =>
      row(
        `${v}: precision / recall`,
        (s) => `${pct(s.perVerdict[v].precision)} / ${pct(s.perVerdict[v].recall)}`,
      ),
    ),
    row("Sample", (s) => `${s.units} messages, ${s.truthClaims} true claims`),
  ].join("\n");
}

async function main(): Promise<void> {
  const local = await pickOllamaModel(io.env);
  const model = local ? `ollama:${local}` : null;
  const synthetic = await runSynthetic({ llm: false, io });
  const syntheticLlm = model ? await runSynthetic({ llm: true, io, model }) : null;
  const flags = flagScores(synthetic);
  const realPatterns = await realScores(null);
  const realLlm = model && realPatterns ? await realScores(model) : null;
  const date = new Date().toISOString().slice(0, 10);

  const md = [
    "# Evaluation",
    "",
    `Generated by \`npm run eval\` on ${date}. Receipts never decides a verdict with a model; the`,
    "model column only changes which claims are found.",
    "",
    "**False-verified rate** is the share of claims Receipts marked verified that were not",
    "actually verified. It is the number this tool exists to keep low.",
    "",
    "## Hand-written cases",
    "",
    `${synthetic.length} synthetic sessions in both formats, written to cover every verdict, every flag and the`,
    "tricky cases (stale after an edit, fail then fix, chained commands, no tests found, sub-agent runs,",
    "interrupted and denied runs, filtered runs, skipped tests, rewritten tests, secrets).",
    "",
    table([
      ["Patterns only", score(synthetic.map((o) => o.unit))],
      [
        model ? `Patterns + ${model}` : "Patterns + model",
        syntheticLlm ? score(syntheticLlm.map((o) => o.unit)) : null,
      ],
    ]),
    "",
    `Flags: precision ${pct(flags.precision)}, recall ${pct(flags.recall)} over ${flags.expected} expected flags.`,
    "",
    "These cases were written alongside the code, so they show the checks do what they are meant",
    "to; they are not an independent measure. The real-session numbers below are.",
    "",
    "## Real sessions",
    "",
  ];
  if (realPatterns) {
    md.push(
      `Agent sessions from the author's machine, ${LABELLED_BY[readLabels().provenance ?? "hand"]} The`,
      "labels and transcripts stay in `eval/private/` and are not committed. Each message is one",
      "turn: a request and the work up to the agent's reply.",
      "",
      table([
        ["Patterns only", realPatterns],
        [model ? `Patterns + ${model}` : "Patterns + model", realLlm],
      ]),
      "",
      `**${realPatterns.unitsWithProblems} of ${realPatterns.units} real messages (${pct(realPatterns.unitsWithProblems / realPatterns.units)}) contain at least one claim that is truly contradicted, stale or unverified.**`,
      "",
    );
  } else {
    md.push(
      `No labels yet. Run \`npm run label\` to create ${path.relative(ROOT, LABELS_FILE)}.`,
      "",
    );
  }
  md.push(
    "## Limitations",
    "",
    "- Small samples. The real-session numbers come from one person's sessions with two agents.",
    "- Labels are one judgement, made while looking at Receipts' own verdict and evidence.",
    "- Extraction recall counts claims the labeller noticed were missed; claims nobody noticed are not counted.",
    "- The patterns are English-only. A message in another language yields few or no claims.",
    "- Real sessions are re-checked against their repositories as they are now. A repository moved or",
    "  deleted since labelling loses its git diff, and claims that relied on it can drop to unverified.",
    "- Staleness is about files, not meaning: an edit that cannot affect a test still makes it stale.",
    "",
  );
  writeFileSync(path.join(ROOT, "eval", "results.md"), md.join("\n"));
  process.stdout.write(`${md.join("\n")}\n`);
}

await main();
